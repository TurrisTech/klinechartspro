import { describe, expect, test } from 'bun:test'

import type { Indicator, IndicatorTemplate, KLineData } from 'klinecharts'

import fixture from './fixtures/wscan_r3_trend.json'
import ichimoku from './ichimoku'
import metro, { metroWarmup } from './metro'
import stcNlma, { stcNlmaWarmup } from './stcnlma'
import trendilo, { distanceFromMean } from './trendilo'

// Four C1s of the windicators NNFX scan's 1D leaders -- Ichimoku, Trendilo, the Schaff Trend
// Cycle on NonLag MAs and Metro Advanced -- against windicators' own output, the code the scan ran
// (fixtures/wscan_r3_trend.json, generated by
// notes/research/NoNonSenseForex/tests/gen_nnfx_r3_trend.py from the windicators snapshot 0b4dcc0).

const bars: KLineData[] = fixture.bars.ts.map((timestamp, i) => ({
  timestamp,
  open: fixture.bars.open[i] as number,
  high: fixture.bars.high[i] as number,
  low: fixture.bars.low[i] as number,
  close: fixture.bars.close[i] as number,
  volume: 1
}))

type Row = Record<string, number | undefined>
const templates = new Map<string, IndicatorTemplate>(
  [ichimoku, trendilo, stcNlma, metro].map((t) => [t.name, t as unknown as IndicatorTemplate])
)
function run(name: string, calcParams: number[], data: KLineData[] = bars): Row[] {
  const t = templates.get(name)
  if (t === undefined) throw new Error(name)
  return (t.calc as (d: KLineData[], i: Indicator) => Row[])(data, { calcParams } as unknown as Indicator)
}
function defaults(name: string): number[] {
  const t = templates.get(name)
  if (t === undefined) throw new Error(name)
  return [...(t.calcParams as number[])]
}

// Each template's calcParams in order, by the names the fixture's `chart` uses; the settings after
// them (inverted, warm-up) keep their defaults unless WARMUP_AT turns the warm-up off.
const PARAM_ORDER: Record<string, string[]> = {
  ICHIMOKU: ['tenkan', 'kijun', 'senkou'],
  TRENDILO: ['smooth', 'length', 'offset', 'sigma', 'ma'],
  STC_NLMA: ['schaff', 'fast', 'slow', 'smooth'],
  METRO: ['period', 'fast', 'slow', 'min_max', 'ma']
}
const WARMUP_AT: Record<string, number> = { TRENDILO: 5, STC_NLMA: 4, METRO: 6 }
const INVERTED_AT: Record<string, number> = { ICHIMOKU: 3, METRO: 5 }

function params(template: string, chart: Record<string, number>, warmOff = true): number[] {
  const p = defaults(template)
  PARAM_ORDER[template].forEach((k, i) => {
    p[i] = chart[k]
  })
  if (warmOff && template in WARMUP_AT) p[WARMUP_AT[template]] = 0
  return p
}

/** 1e-9 relative (the fixture holds 12 significant digits); an exact 0 must be 0. */
function near(actual: number | undefined, expected: number): boolean {
  return actual !== undefined && Math.abs(actual - expected) <= 1e-9 * Math.abs(expected)
}

type Case = (typeof fixture.cases)[number]
function dataOf(c: Case): KLineData[] {
  const own = c as { close?: number[] }
  return own.close === undefined ? bars : bars.map((b, i) => ({ ...b, close: own.close?.[i] as number }))
}

// The sparse outputs: METRO's arrows (a value only where one fires) and its trend, which equal step
// sizes hold blank from the first bar.
const SPARSE = new Set(['trend_up_arrow', 'trend_dn_arrow', 'cross_fast_up', 'cross_fast_dn', 'cross_slow_up', 'cross_slow_dn', 'trend'])

describe('parity with windicators, the code the windicators NNFX scan ran', () => {
  test('the fixture is the generated one, and covers every template', () => {
    expect(fixture.$comment).toContain('gen_nnfx_r3_trend.py')
    expect(new Set(fixture.cases.map((c) => c.template))).toEqual(new Set(Object.keys(PARAM_ORDER)))
  })

  test("each template's defaults are the scan's setting, which the fixture checks", () => {
    for (const name of Object.keys(PARAM_ORDER)) {
      const checked = fixture.cases.filter((c) => c.template === name).map((c) => params(name, c.chart as unknown as Record<string, number>, false))
      expect(checked).toContainEqual(defaults(name))
    }
    expect(defaults('ICHIMOKU')).toEqual([4, 20, 21, 1])
    expect(defaults('TRENDILO')).toEqual([6, 25, 0.5695, 7, 8, 1])
    expect(defaults('STC_NLMA')).toEqual([16, 23, 28, 6.6, 1])
    expect(defaults('METRO')).toEqual([42, 2, 30, 49, 3, 1, 1])
  })

  for (const c of fixture.cases) {
    const p = params(c.template, c.chart as unknown as Record<string, number>)
    test(`${c.template}(${p.join(', ')}) -- ${c.source}`, () => {
      const rows = run(c.template, p, dataOf(c))
      const out = c.out as unknown as Record<string, Array<number | null>>
      for (const [key, expected] of Object.entries(out)) {
        const bad: Array<{ i: number; actual: number | undefined; expected: number | null }> = []
        expected.forEach((e, i) => {
          const a = rows[i][key]
          if (e === null ? a !== undefined : !near(a, e)) bad.push({ i, actual: a, expected: e })
        })
        expect({ key, bad: bad.slice(0, 5) }).toEqual({ key, bad: [] })
        if (!SPARSE.has(key)) expect(expected.filter((v) => v !== null).length).toBeGreaterThan(bars.length / 2)
      }
      // The reading: the scan's state wherever the chart draws one, and the chart draws one exactly
      // where its lines are both there (the trigger, or both lines of a pair).
      const bad: Array<{ i: number; actual: number | undefined; expected: number }> = []
      const drawn = (i: number) =>
        c.template === 'ICHIMOKU' ? out.kijun[i] !== null && out.senkou_b[i] !== null : c.template === 'STC_NLMA' ? out.stc[i] !== null : out.ma[i] !== null
      c.state.forEach((s, i) => {
        const a = rows[i].state
        if (drawn(i) ? a !== s : a !== undefined) bad.push({ i, actual: a, expected: s })
      })
      expect(bad.slice(0, 5)).toEqual([])
    })
  }

  test('METRO: the arrows fire somewhere in the fixture, each kind', () => {
    for (const key of SPARSE) {
      const fired = fixture.cases.filter((c) => c.template === 'METRO').some((c) => (c.out as unknown as Record<string, Array<number | null>>)[key].some((v) => v !== null))
      expect({ key, fired }).toEqual({ key, fired: true })
    }
  })
})

// A history long enough to leave every warm-up: a deterministic random walk, 2,000 daily bars.
const long: KLineData[] = (() => {
  let x = 1.1
  let seed = 7
  return Array.from({ length: 2000 }, (_, i) => {
    seed = (seed * 1103515245 + 12345) % 2147483648
    const prev = x
    x *= 1 + (seed / 2147483648 - 0.5) * 0.02
    return { timestamp: i * 86400000, open: prev, high: Math.max(prev, x) * 1.002, low: Math.min(prev, x) * 0.998, close: x, volume: 1 }
  })
})()

describe('the readings the scan tested', () => {
  test('ICHIMOKU: the state is the kijun against senkou B, flipped by "inverted", a tie being no signal', () => {
    for (const inverted of [0, 1]) {
      const p = defaults('ICHIMOKU')
      p[INVERTED_AT.ICHIMOKU] = inverted
      const dir = inverted === 1 ? -1 : 1
      const rows = run('ICHIMOKU', p, long)
      for (const r of rows) {
        if (r.kijun === undefined || r.senkou_b === undefined) expect(r.state).toBeUndefined()
        else expect(r.state).toBe(r.kijun === r.senkou_b ? 0 : dir * Math.sign(r.kijun - r.senkou_b))
      }
      expect(new Set(rows.map((r) => r.state))).toEqual(new Set([undefined, 0, 1, -1]))
    }
  })

  test('ICHIMOKU: kijun 20 and senkou 21 differ only through the bar 20 back', () => {
    const rows = run('ICHIMOKU', defaults('ICHIMOKU'), long)
    rows.forEach((r, i) => {
      if (r.state === undefined) return
      const hi20 = Math.max(...long.slice(i - 19, i + 1).map((b) => b.high))
      const lo20 = Math.min(...long.slice(i - 19, i + 1).map((b) => b.low))
      const up = Math.max(0, long[i - 20].high - hi20)
      const down = Math.max(0, lo20 - long[i - 20].low)
      // Inverted: long while senkou B is above the kijun, i.e. the bar 20 back pokes out more above than below.
      expect(r.state).toBe(up > down ? 1 : up < down ? -1 : 0)
    })
  })

  const crosses: Array<[string, string]> = [['TRENDILO', 'trendilo'], ['METRO', 'level_up']]
  for (const [name, key] of crosses) {
    test(`${name}: the state is ${key} against its exact trigger mean${name in INVERTED_AT ? ', flipped by "inverted"' : ''}`, () => {
      for (const inverted of name in INVERTED_AT ? [0, 1] : [0]) {
        const p = defaults(name)
        if (name in INVERTED_AT) p[INVERTED_AT[name]] = inverted
        const dir = name in INVERTED_AT && inverted === 1 ? -1 : 1
        const rows = run(name, p, long)
        const line = rows.map((r) => r[key] ?? Number.NaN)
        const dist = distanceFromMean(line, p[4])
        rows.forEach((r, i) => {
          if (!Number.isFinite(dist[i])) expect(r.state).toBeUndefined()
          else expect(r.state).toBe(dist[i] === 0 ? 0 : dir * Math.sign(dist[i]))
        })
        const sides = new Set(rows.map((r) => r.state).filter((s) => s !== undefined))
        // Both sides; METRO's level also holds still (no signal), a continuous TRENDILO never does.
        expect(sides).toEqual(new Set(name === 'METRO' ? [1, -1, 0] : [1, -1]))
      }
    })
  }

  test('STC_NLMA: the state is stc against 50, and both sides occur', () => {
    const rows = run('STC_NLMA', defaults('STC_NLMA'), long)
    for (const r of rows) if (r.stc !== undefined) expect(r.state).toBe(Math.sign(r.stc - 50))
    expect(new Set(rows.map((r) => r.state).filter((s) => s !== undefined))).toEqual(new Set([1, -1]))
  })

  test("the exact trigger mean sums its window in numpy's order, to the last bit (the fixture's probes)", () => {
    for (const probe of fixture.probes) {
      const d = distanceFromMean(probe.x, probe.k).map((v) => (Number.isNaN(v) ? null : v))
      expect({ k: probe.k, n: probe.x.length, d }).toEqual({ k: probe.k, n: probe.x.length, d: probe.d })
    }
  })

  test('the exact trigger mean: a line that has held one value for k bars reads exactly 0', () => {
    const x = [1.1, 0.3, 0.7, 0.7, 0.7, 0.7, 0.7, 0.7, 0.7, 0.7, 0.2]
    expect(distanceFromMean(x, 8)[9]).toBe(0)
    expect(distanceFromMean(x, 3)[4]).toBe(0)
    expect(distanceFromMean(x, 3)[10]).toBeLessThan(0)
    expect(Number.isNaN(distanceFromMean([1, Number.NaN, 2, 3], 2)[2])).toBe(true)
  })
})

describe('causal: a run on a prefix of the bars is the prefix of the full run', () => {
  for (const name of Object.keys(PARAM_ORDER)) {
    for (const warm of [0, 1]) {
      test(`${name}, warm-up ${name in WARMUP_AT ? warm : 'none'}`, () => {
        const p = defaults(name)
        if (name in WARMUP_AT) p[WARMUP_AT[name]] = warm
        const full = run(name, p, long)
        for (const n of [30, 237, 480, 1001]) expect(run(name, p, long.slice(0, n))).toEqual(full.slice(0, n))
      })
    }
  }
})

describe('warm-up', () => {
  test('TRENDILO: the start-up spike blanked until smooth + length - 1, the band length - 1 bars later, the reading ma - 1 bars after the line', () => {
    const on = run('TRENDILO', defaults('TRENDILO'), long)
    const p = defaults('TRENDILO')
    p[5] = 0
    const off = run('TRENDILO', p, long)
    expect(defaults('TRENDILO')[5]).toBe(1)
    on.forEach((r, i) => {
      if (i < 30) expect(r).toEqual({})
      else if (i < 37) expect(r).toEqual({ trendilo: off[i].trendilo })
      else if (i < 54) expect(r).toEqual({ trendilo: off[i].trendilo, ma: off[i].ma, state: off[i].state })
      else expect(r).toEqual(off[i])
    })
    // What it hides: windicators' line from bar 24, inflated by the 0 the source reads before the
    // oldest close. On the fixture's EURUSD bars bar 24 is above every bar after the warm-up.
    expect(off[23].trendilo).toBeUndefined()
    const raw = run('TRENDILO', p).map((r) => Math.abs(r.trendilo ?? 0))
    expect(raw[24]).toBeGreaterThan(Math.max(...raw.slice(30)))
  })

  test('STC_NLMA: blank until the NonLag averages are exact, both windows filled and both seeds below 1e-4', () => {
    expect(stcNlmaWarmup(16, 23, 28, 6.6)).toBe(230)
    expect(stcNlmaWarmup(32, 23, 50, 3)).toBe(338)
    expect(stcNlmaWarmup(16, 4, 3, 6.6)).toBe(92)
    expect(stcNlmaWarmup(10, 12, 26, 1)).toBe(18 + 128)
    const on = run('STC_NLMA', defaults('STC_NLMA'), long)
    const p = defaults('STC_NLMA')
    p[4] = 0
    const off = run('STC_NLMA', p, long)
    expect(defaults('STC_NLMA')[4]).toBe(1)
    on.forEach((r, i) => {
      if (i < 230) expect(r).toEqual({})
      else expect(r).toEqual(off[i])
    })
    expect(off[0].stc).toBeDefined()
  })

  test('METRO: blank until the RSI seed is below 1e-4 and the levels window has passed it; the reading ma - 1 bars later', () => {
    expect(metroWarmup(42, 49)).toBe(472)
    expect(metroWarmup(14, 49)).toBe(13 + 125 + 48)
    const on = run('METRO', defaults('METRO'), long)
    const p = defaults('METRO')
    p[6] = 0
    const off = run('METRO', p, long)
    expect(defaults('METRO')[6]).toBe(1)
    on.forEach((r, i) => {
      if (i < 472) expect(r).toEqual({})
      else if (i < 474) {
        const { ma: _ma, state: _state, ...lines } = off[i]
        expect(r).toEqual(lines)
      } else expect(r).toEqual(off[i])
    })
    // Without it: the RSI from bar 1, the levels from bar min-max (49), where their window has left the oldest bar.
    expect(off[0]).toEqual({})
    expect(off[1].rsi).toBeDefined()
    expect(off[48].level_up).toBeUndefined()
    expect(off[49].level_up).toBeLessThanOrEqual(100)
  })
})
