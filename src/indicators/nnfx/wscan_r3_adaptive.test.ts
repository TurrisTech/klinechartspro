import { describe, expect, test } from 'bun:test'

import type { Indicator, IndicatorTemplate, KLineData } from 'klinecharts'

import { adaptiveBp, adaptiveBpCube, adaptiveBpCubeSettings, adaptiveBpSettings } from './adaptivebandpass'
import adaptiveRsi, { adaptiveRsiSettings } from './adaptiversi'
import { bandPassWarmup, numpySum, rsiWarmup, versusMean } from './ehlersadaptive'
import fixture from './fixtures/wscan_r3_adaptive.json'

// The Ehlers adaptive templates of the windicators NNFX scan's round 3 (ADAPT_BP, ADAPT_BP_CUBE,
// ADAPT_RSI), against windicators' own output -- the code the scan ran
// (fixtures/wscan_r3_adaptive.json, generated by
// notes/research/NoNonSenseForex/tests/gen_nnfx_r3_adaptive.py from the windicators snapshot 0b4dcc0).

const bars: KLineData[] = fixture.bars.ts.map((timestamp, i) => ({
  timestamp,
  open: fixture.bars.open[i] as number,
  high: fixture.bars.high[i] as number,
  low: fixture.bars.low[i] as number,
  close: fixture.bars.close[i] as number,
  volume: fixture.bars.volume[i] as number
}))

type Row = Record<string, number | undefined>
// biome-ignore lint/suspicious/noExplicitAny: the three templates' row types differ
const templates = new Map<string, IndicatorTemplate<any, number>>([adaptiveBp, adaptiveBpCube, adaptiveRsi].map((t) => [t.name, t]))
function run(name: string, calcParams: number[], data: KLineData[] = bars): Row[] {
  const t = templates.get(name)
  if (t === undefined) throw new Error(name)
  return (t.calc as (d: KLineData[], i: Indicator) => Row[])(data, { calcParams } as unknown as Indicator)
}
function defaults(name: string): number[] {
  const t = templates.get(name)
  if (t === undefined) throw new Error(name)
  return [...(t.calcParams as number[])]
}

// Each template's calcParams in order, by the names the fixture's `chart` uses; the trailing
// `inverted` and `warm-up` keep their defaults unless set.
const PARAM_ORDER: Record<string, string[]> = {
  ADAPT_BP: ['bandwidth', 'avg_length', 'hp_period', 'lp_period', 'ma'],
  ADAPT_BP_CUBE: ['bandwidth', 'avg_length', 'hp_period', 'lp_period'],
  ADAPT_RSI: ['avg_length', 'hp_period', 'lp_period', 'ma']
}
// Where `inverted` and `warm-up` sit in each template's calcParams.
const INVERTED_AT: Record<string, number> = { ADAPT_BP: 5, ADAPT_BP_CUBE: 4, ADAPT_RSI: 4 }
const WARMUP_AT: Record<string, number> = { ADAPT_BP: 6, ADAPT_BP_CUBE: 5, ADAPT_RSI: 5 }
// The line each reading is taken on.
const LINE: Record<string, string> = { ADAPT_BP: 'signal', ADAPT_BP_CUBE: 'cube', ADAPT_RSI: 'rsi' }

function params(template: string, chart: Record<string, number>): number[] {
  const p = defaults(template)
  PARAM_ORDER[template].forEach((k, i) => {
    p[i] = chart[k]
  })
  return p
}

function near(actual: number | undefined, expected: number): boolean {
  return actual !== undefined && Math.abs(actual - expected) <= 1e-9 * Math.max(1, Math.abs(expected))
}

describe('parity with windicators, the code the windicators NNFX scan ran', () => {
  test('the fixture is the generated one, and covers every template', () => {
    expect(fixture.$comment).toContain('gen_nnfx_r3_adaptive.py')
    expect(new Set(fixture.cases.map((c) => c.template))).toEqual(new Set(Object.keys(PARAM_ORDER)))
  })

  test("each template's defaults are the scan's setting, the first case the fixture checks", () => {
    expect(defaults('ADAPT_BP')).toEqual([0.3, 6, 24, 15, 8, 1, 1])
    expect(defaults('ADAPT_BP_CUBE')).toEqual([0.1608, 6, 24, 15, 1, 1])
    expect(defaults('ADAPT_RSI')).toEqual([3, 36, 20, 8, 0, 1])
    for (const name of Object.keys(PARAM_ORDER)) {
      const first = fixture.cases.find((c) => c.template === name)
      expect(first).toBeDefined()
      expect(params(name, first?.chart as unknown as Record<string, number>)).toEqual(defaults(name))
    }
  })

  for (const c of fixture.cases) {
    const p = params(c.template, c.chart as unknown as Record<string, number>)
    // The 250 fixture bars are all inside the templates' warm-ups, so parity is checked with it off.
    p[WARMUP_AT[c.template]] = 0
    test(`${c.template}(${p.join(', ')}) -- ${c.source}`, () => {
      const rows = run(c.template, p)
      const out = c.out as unknown as Record<string, Array<number | null>>
      for (const [key, expected] of Object.entries(out)) {
        const bad: Array<{ i: number; actual: number | undefined; expected: number | null }> = []
        expected.forEach((e, i) => {
          const a = rows[i][key]
          const ok = e === null ? a === undefined : key === 'state' ? a === e : near(a, e)
          if (!ok) bad.push({ i, actual: a, expected: e })
        })
        expect({ key, bad: bad.slice(0, 5) }).toEqual({ key, bad: [] })
        expect(expected.filter((v) => v !== null).length).toBeGreaterThan(bars.length * 0.6)
      }
      // The rows carry nothing the fixture does not check.
      for (const r of rows) for (const k of Object.keys(r)) expect(Object.keys(out)).toContain(k)
    })
  }

  test('the fixture reaches the tie (a line held for the whole window reads 0) on both ma readings', () => {
    const zeros = (name: string) =>
      fixture.cases.filter((c) => c.template === name).flatMap((c) => (c.out as unknown as Record<string, Array<number | null>>).state.filter((s) => s === 0))
    expect(zeros('ADAPT_BP').length).toBeGreaterThan(0)
    expect(zeros('ADAPT_RSI').length).toBeGreaterThan(0)
  })
})

describe('the readings the scan tested', () => {
  for (const name of Object.keys(PARAM_ORDER)) {
    test(`${name}: "inverted" swaps long and short exactly, and a tie stays 0`, () => {
      const base = defaults(name)
      base[WARMUP_AT[name]] = 0
      const conventional = [...base]
      conventional[INVERTED_AT[name]] = 0
      const inverted = [...base]
      inverted[INVERTED_AT[name]] = 1
      const a = run(name, conventional)
      const b = run(name, inverted)
      a.forEach((r, i) => {
        if (r.state === undefined) expect(b[i].state).toBeUndefined()
        else expect(Object.is(b[i].state, r.state === 0 ? 0 : -r.state)).toBe(true)
      })
      const sides = new Set(a.map((r) => r.state))
      expect(sides.has(1) && sides.has(-1)).toBe(true)
    })
  }

  test('ADAPT_BP and ADAPT_RSI: the state is the line against its exact mean, flipped by "inverted"', () => {
    for (const name of ['ADAPT_BP', 'ADAPT_RSI']) {
      const p = defaults(name)
      p[WARMUP_AT[name]] = 0
      const rows = run(name, p)
      const dir = p[INVERTED_AT[name]] >= 1 ? -1 : 1
      const line = rows.map((r) => r[LINE[name]] ?? Number.NaN)
      const { vs } = versusMean(line, p[PARAM_ORDER[name].indexOf('ma')])
      rows.forEach((r, i) => {
        if (r.state === undefined) return
        expect(r.state).toBe(vs[i] > 0 ? dir : vs[i] < 0 ? -dir : 0)
        // The drawn mean is the window's mean, so the side is the line's side of it (ties aside).
        if (r.state !== 0) expect(Math.sign((r[LINE[name]] as number) - (r.ma as number))).toBe(dir * r.state)
      })
    }
  })

  test('ADAPT_BP_CUBE: the state is the cube against zero, inverted', () => {
    const p = defaults('ADAPT_BP_CUBE')
    p[WARMUP_AT.ADAPT_BP_CUBE] = 0
    for (const r of run('ADAPT_BP_CUBE', p)) if (r.cube !== undefined) expect(r.state).toBe(-Math.sign(r.cube) || 0)
  })

  test("the exact mean adds in numpy's order: a value held for the window reads exactly 0", () => {
    const x = [0.1, 0.2, 0.3, 0.7, 0.7, 0.7, 0.7, 0.7, 0.7, 0.7, 0.7, 0.4]
    const { vs } = versusMean(x, 8)
    expect(vs[10]).toBe(0)
    expect(vs[9]).not.toBe(0)
    // numpy's pairwise sum of eight is ((0+1)+(2+3))+((4+5)+(6+7)); fewer than eight, left to right.
    const a = [1e16, 1, -1e16, 1, 3, -2, 0.5, 7]
    expect(numpySum(a, 0, 8)).toBe(a[0] + a[1] + (a[2] + a[3]) + (a[4] + a[5] + (a[6] + a[7])))
    expect(numpySum(a, 0, 3)).toBe(a[0] + a[1] + a[2])
  })
})

describe('causal: a run on a prefix of the bars is the prefix of the full run', () => {
  for (const name of Object.keys(PARAM_ORDER)) {
    for (const c of fixture.cases.filter((k) => k.template === name).slice(0, 3)) {
      const p = params(name, c.chart as unknown as Record<string, number>)
      p[WARMUP_AT[name]] = 0
      test(`${name}(${p.join(', ')})`, () => {
        const full = run(name, p)
        for (const n of [40, 97, 180, 249]) expect(run(name, p, bars.slice(0, n))).toEqual(full.slice(0, n))
      })
    }
  }
})

describe('the warm-up', () => {
  // 800 bars: the fixture's 250, then a deterministic walk on from its last close.
  const long: KLineData[] = [...bars]
  let seed = 7
  for (let i = bars.length; i < 800; i++) {
    seed = (seed * 16807) % 2147483647
    const prev = long[i - 1].close
    const close = prev * (1 + 0.006 * (seed / 2147483647 - 0.5))
    long.push({ timestamp: long[i - 1].timestamp + 86400000, open: prev, high: Math.max(prev, close) * 1.002, low: Math.min(prev, close) * 0.998, close, volume: 1 })
  }

  test('the helpers give what the doc comments say', () => {
    expect(bandPassWarmup(24, 0.3)).toBe(232)
    expect(bandPassWarmup(24, 0.1608)).toBe(284)
    expect(bandPassWarmup(48, 0.3)).toBe(364)
    expect(rsiWarmup(36)).toBe(228)
    expect(rsiWarmup(48)).toBe(264)
    expect(adaptiveBpSettings(defaults('ADAPT_BP')).warm).toBe(232)
    expect(adaptiveBpCubeSettings(defaults('ADAPT_BP_CUBE')).warm).toBe(284)
    expect(adaptiveRsiSettings(defaults('ADAPT_RSI')).warm).toBe(228)
    const off = (name: string) => {
      const p = defaults(name)
      p[WARMUP_AT[name]] = 0
      return p
    }
    expect(adaptiveBpSettings(off('ADAPT_BP')).warm).toBe(0)
    expect(adaptiveBpCubeSettings(off('ADAPT_BP_CUBE')).warm).toBe(0)
    expect(adaptiveRsiSettings(off('ADAPT_RSI')).warm).toBe(0)
  })

  for (const name of Object.keys(PARAM_ORDER)) {
    test(`${name}: blank before the warm-up's bar, the same as with it off from there`, () => {
      const on = defaults(name)
      const off = [...on]
      off[WARMUP_AT[name]] = 0
      const warm = name === 'ADAPT_RSI' ? adaptiveRsiSettings(on).warm : name === 'ADAPT_BP' ? adaptiveBpSettings(on).warm : adaptiveBpCubeSettings(on).warm
      const a = run(name, on, long)
      const b = run(name, off, long)
      expect(a.slice(0, warm).every((r) => Object.keys(r).length === 0)).toBe(true)
      expect(b.slice(0, warm).some((r) => r.state !== undefined)).toBe(true)
      expect(a.slice(warm)).toEqual(b.slice(warm))
      expect(a[warm].state).toBeDefined()
      // On the fixture's 250 bars too (ADAPT_BP_CUBE's 284 covers them all).
      const short = run(name, on)
      expect(short.slice(0, warm).every((r) => Object.keys(r).length === 0)).toBe(true)
      expect(short.slice(warm)).toEqual(run(name, off).slice(warm))
    })
  }
})
