import { describe, expect, test } from 'bun:test'

import type { Indicator, IndicatorTemplate, KLineData } from 'klinecharts'

import bandStop, { bandStopWarmup } from './bandstop'
import fixture from './fixtures/wscan_r3_cycle.json'
import prc from './prc'
import swamiSwing, { swamiWarmup, vsMean } from './swami'
import truncBp, { truncWarmup } from './truncbp'

// The windicators NNFX scan's round-3 cycle filters -- the SwamiCharts swing wave, the truncated
// band-pass, the band-stop filter and the polynomial regression channel -- against windicators'
// own output, the code the scan ran (fixtures/wscan_r3_cycle.json, generated by
// notes/research/NoNonSenseForex/tests/gen_nnfx_r3_cycle.py from the windicators snapshot 0b4dcc0).

const bars: KLineData[] = fixture.bars.ts.map((timestamp, i) => ({
  timestamp,
  open: fixture.bars.open[i] as number,
  high: fixture.bars.high[i] as number,
  low: fixture.bars.low[i] as number,
  close: fixture.bars.close[i] as number,
  volume: fixture.bars.volume[i] as number
}))

type Row = Record<string, number | undefined>
const templates = new Map<string, IndicatorTemplate>(
  [swamiSwing, truncBp, bandStop, prc].map((t) => [t.name, t as unknown as IndicatorTemplate])
)
function run(name: string, calcParams: number[], data: KLineData[] = bars): Row[] {
  const t = templates.get(name)
  if (t === undefined) throw new Error(name)
  return (t.calc as (d: KLineData[], i: Indicator) => Row[])(data, { calcParams } as unknown as Indicator)
}
function defaults(name: string): number[] {
  const t = templates.get(name)
  if (t === undefined) throw new Error(name)
  return [...(t.calcParams as number[])]
}

// Each template's calcParams in order, by the names the fixture's `chart` uses; the trailing
// warm-up setting keeps its default unless WARMUP_AT turns it off.
const PARAM_ORDER: Record<string, string[]> = {
  SWAMI_SWING: ['period', 'delta', 'ma', 'inverted'],
  TRUNC_BP: ['period', 'bandwidth', 'length', 'inverted'],
  BANDSTOP: ['period', 'delta'],
  PRC: ['degree', 'period', 'deviations1', 'deviations2', 'redraw', 'inverted']
}
// The 250 fixture bars are inside the IIR templates' warm-ups, so parity is checked with them off;
// the warm-ups themselves are tested below.
const WARMUP_AT: Record<string, number> = { SWAMI_SWING: 4, TRUNC_BP: 4, BANDSTOP: 2 }

function params(template: string, chart: Record<string, number>, warmOff = true): number[] {
  const p = defaults(template)
  PARAM_ORDER[template].forEach((k, i) => {
    p[i] = chart[k]
  })
  if (warmOff && template in WARMUP_AT) p[WARMUP_AT[template]] = 0
  return p
}

/** The sign of `d` after `dir`, a tie being +0 (toBe tells -0 from 0). */
function side(d: number, dir: number): number {
  return Math.sign(d) === 0 ? 0 : dir * Math.sign(d)
}

/** 1e-9 relative (the fixture holds 12 significant digits); an exact 0 must be 0. */
function near(actual: number | undefined, expected: number): boolean {
  return actual !== undefined && Math.abs(actual - expected) <= 1e-9 * Math.abs(expected)
}

type Case = (typeof fixture.cases)[number]
function data(c: Case): KLineData[] {
  const own = c as { high?: number[]; low?: number[] }
  return bars.map((b, i) => ({ ...b, high: own.high === undefined ? b.high : own.high[i], low: own.low === undefined ? b.low : own.low[i] }))
}

/** The fixture output `key` of a case against the template's row field `field`; returns the mismatches. */
function compare(rows: Row[], field: string, expected: Array<number | null>, exact: boolean) {
  const bad: Array<{ i: number; actual: number | undefined; expected: number | null }> = []
  expected.forEach((e, i) => {
    const a = rows[i][field]
    const ok = e === null ? a === undefined : exact ? a === e : near(a, e)
    if (!ok) bad.push({ i, actual: a, expected: e })
  })
  return bad.slice(0, 5)
}

describe('parity with windicators, the code the windicators NNFX scan ran', () => {
  test('the fixture is the generated one, and covers every template', () => {
    expect(fixture.$comment).toContain('gen_nnfx_r3_cycle.py')
    expect(new Set(fixture.cases.map((c) => c.template))).toEqual(new Set(Object.keys(PARAM_ORDER)))
  })

  test("each template's defaults are the scan's setting, and a case the fixture checks", () => {
    expect(defaults('SWAMI_SWING')).toEqual([33, 0.1, 8, 0, 1])
    expect(defaults('TRUNC_BP')).toEqual([30, 0.15, 11, 1, 1])
    expect(defaults('BANDSTOP')).toEqual([24, 0.067, 1])
    expect(defaults('PRC')).toEqual([2, 300, 1.08406, 1.34, 1, 1])
    for (const name of Object.keys(PARAM_ORDER)) {
      const checked = fixture.cases.filter((c) => c.template === name).map((c) => params(name, c.chart as unknown as Record<string, number>, false))
      expect(checked).toContainEqual(defaults(name))
    }
    // Band-stop's other setting, the best standalone baseline and systems 3 and 5's.
    expect(fixture.cases.filter((c) => c.template === 'BANDSTOP').map((c) => c.chart)).toContainEqual({ period: 30, delta: 0.067 })
    // The swing wave's C2 reading in the best system: the 36-bar line at delta 0.067 against zero, inverted.
    expect(fixture.cases.filter((c) => c.template === 'SWAMI_SWING').map((c) => c.chart)).toContainEqual({ period: 36, delta: 0.067, ma: 0, inverted: 1 })
  })

  for (const c of fixture.cases) {
    const chart = c.chart as unknown as Record<string, number>
    const p = params(c.template, chart)
    const out = c.out as unknown as Record<string, Array<number | null>>
    test(`${c.template}(${p.join(', ')}) -- ${c.source}`, () => {
      const rows = run(c.template, p, data(c))
      let checked = 0
      for (const [key, expected] of Object.entries(out)) {
        let r = rows
        let field = key
        // The swing wave's fixture holds a line per period, bp<N>; the template draws one, `bp`.
        const line = c.template === 'SWAMI_SWING' ? /^bp(\d+)$/.exec(key) : null
        if (line !== null) {
          const q = [...p]
          q[0] = Number(line[1])
          r = run(c.template, q, data(c))
          field = 'bp'
        }
        expect({ key, bad: compare(r, field, expected, key === 'state') }).toEqual({ key, bad: [] })
        checked += expected.filter((v) => v !== null).length
      }
      // The default PRC's 301-bar window is longer than the fixture: it checks that nothing is drawn.
      if (c.template === 'PRC' && chart.period >= bars.length) expect(rows.every((r) => Object.keys(r).length === 0)).toBe(true)
      else expect(checked).toBeGreaterThan(0)
    })
  }

  test('the swing wave reads the line against its mean in numpy summation order, bit for bit', () => {
    const x = fixture.vs_sma.x
    for (const [k, expected] of Object.entries(fixture.vs_sma.out)) {
      const actual = vsMean(x, Number(k))
      expected.forEach((e, i) => {
        if (e === null) expect(Number.isNaN(actual[i])).toBe(true)
        else expect(actual[i]).toBe(e)
      })
    }
  })

  test('the long-window cases have values where windicators does, and only there', () => {
    const rows = run('PRC', [2, 240, 1.08406, 1.34, 1, 1])
    expect(rows.filter((r) => r.middle !== undefined).length).toBe(10)
    const swami = run('SWAMI_SWING', [12, 0.05, 200, 0, 0])
    expect(swami.filter((r) => r.state !== undefined).length).toBe(bars.length - 201)
  })
})

describe('causality: a run on a prefix of the bars is the prefix of the full run', () => {
  const settings: Array<[string, number[]]> = [
    ['SWAMI_SWING', [33, 0.1, 8, 0, 0]],
    ['SWAMI_SWING', [36, 0.067, 0, 1, 0]],
    ['TRUNC_BP', [30, 0.15, 11, 1, 0]],
    ['BANDSTOP', [24, 0.067, 0]],
    ['BANDSTOP', [30, 0.067, 0]],
    ['PRC', [2, 100, 1.08406, 1.34, 1, 1]],
    ['PRC', [3, 30, 1.618, 2, 0, 1]]
  ]
  for (const [name, p] of settings) {
    test(`${name}(${p.join(', ')})`, () => {
      const full = run(name, p)
      for (const n of [1, 3, 20, 61, 150, 201, 249]) expect(run(name, p, bars.slice(0, n))).toEqual(full.slice(0, n))
    })
  }
})

describe('the readings the scan tested', () => {
  test('SWAMI_SWING: against its mean, the state is the sign of the vs_sma distance, flipped by "inverted"', () => {
    for (const inverted of [0, 1]) {
      const rows = run('SWAMI_SWING', [33, 0.1, 8, inverted, 0])
      const bp = rows.map((r) => r.bp ?? Number.NaN)
      const d = vsMean(bp, 8)
      const dir = inverted === 1 ? -1 : 1
      rows.forEach((r, i) => {
        if (Number.isFinite(d[i])) expect(r.state).toBe(side(d[i], dir))
        else expect(r.state).toBeUndefined()
      })
      expect(new Set(rows.map((r) => r.state).filter((s) => s !== undefined))).toEqual(new Set([1, -1]))
    }
  })

  test('SWAMI_SWING: ma 0 or 1 reads the line against zero, and draws no mean', () => {
    for (const ma of [0, 1]) {
      const rows = run('SWAMI_SWING', [36, 0.067, ma, 1, 0])
      for (const r of rows) {
        expect(r.ma).toBeUndefined()
        if (r.bp !== undefined) expect(r.state).toBe(side(r.bp, -1))
      }
    }
  })

  test('SWAMI_SWING: a line that has held one value for ma bars reads exactly 0, never -0', () => {
    const c = fixture.cases.find((x) => x.template === 'SWAMI_SWING' && (x as { high?: number[] }).high !== undefined) as Case
    const rows = run('SWAMI_SWING', [33, 0.1, 8, 1, 0], data(c))
    for (let i = 9; i < 120; i++) expect(Object.is(rows[i].state, 0)).toBe(true)
  })

  test('TRUNC_BP: the state is the truncated line against the standard one, flipped by "inverted"', () => {
    for (const inverted of [0, 1]) {
      const rows = run('TRUNC_BP', [30, 0.15, 11, inverted, 0])
      const dir = inverted === 1 ? -1 : 1
      for (const r of rows) {
        if (r.bpt !== undefined && r.bp !== undefined) expect(r.state).toBe(side(r.bpt - r.bp, dir))
        else expect(r.state).toBeUndefined()
      }
      // Bar length + 2 is a tie: there bpt is bp's own recursion from bar 3, from the same zeros.
      expect(rows[13].bpt).toBe(rows[13].bp as number)
      expect(Object.is(rows[13].state, 0)).toBe(true)
      expect(new Set(rows.filter((_, i) => i !== 13).map((r) => r.state).filter((s) => s !== undefined))).toEqual(new Set([1, -1]))
    }
  })

  test('BANDSTOP: the state is the close against the line, and takes both sides', () => {
    for (const p of [24, 30]) {
      const rows = run('BANDSTOP', [p, 0.067, 0])
      rows.forEach((r, i) => {
        if (r.bs !== undefined) expect(r.state).toBe(side(bars[i].close - r.bs, 1))
      })
    }
  })

  test('PRC: the state is the close against the middle line, flipped by "inverted"', () => {
    for (const inverted of [0, 1]) {
      const rows = run('PRC', [2, 100, 1.08406, 1.34, 1, inverted])
      const dir = inverted === 1 ? -1 : 1
      rows.forEach((r, i) => {
        if (r.middle !== undefined) expect(r.state).toBe(side(bars[i].close - r.middle, dir))
        else expect(r.state).toBeUndefined()
      })
      expect(new Set(rows.map((r) => r.state).filter((s) => s !== undefined))).toEqual(new Set([1, -1]))
    }
  })

  test('PRC: redraw does not move the line, only the bands, which redraw off leaves blank until bar 2 x period', () => {
    const on = run('PRC', [2, 100, 1.08406, 1.34, 1, 1])
    const off = run('PRC', [2, 100, 1.08406, 1.34, 0, 1])
    on.forEach((r, i) => {
      expect(off[i].middle).toBe(r.middle as number)
      if (i < 200) expect(off[i].upper1).toBeUndefined()
      else expect(off[i].upper1).toBeDefined()
    })
  })
})

describe('warm-up', () => {
  // A history long enough to leave the warm-ups: a deterministic random walk.
  const long: KLineData[] = (() => {
    let x = 1.1
    let seed = 7
    return Array.from({ length: 2000 }, (_, i) => {
      seed = (seed * 1103515245 + 12345) % 2147483648
      x *= 1 + (seed / 2147483648 - 0.5) * 0.01
      return { timestamp: i * 86400000, open: x, high: x * 1.002, low: x * 0.998, close: x, volume: 1 }
    })
  })()

  test('the bounds the doc comments state', () => {
    expect(swamiWarmup(33, 0.1)).toBe(244)
    expect(swamiWarmup(36, 0.067)).toBe(396)
    expect(truncWarmup(30, 0.15, 11)).toBe(297)
    expect(bandStopWarmup(24, 0.067)).toBe(659)
    expect(bandStopWarmup(30, 0.067)).toBe(823)
    // bpt's own start bounds the truncated band-pass where bp's decay is shorter.
    expect(truncWarmup(4, 0.9, 98)).toBe(99)
  })

  const cases: Array<[string, number[], number]> = [
    ['SWAMI_SWING', [33, 0.1, 8, 0], swamiWarmup(33, 0.1)],
    ['SWAMI_SWING', [36, 0.067, 0, 1], swamiWarmup(36, 0.067)],
    ['TRUNC_BP', [30, 0.15, 11, 1], truncWarmup(30, 0.15, 11)],
    ['BANDSTOP', [24, 0.067], bandStopWarmup(24, 0.067)],
    ['BANDSTOP', [30, 0.067], bandStopWarmup(30, 0.067)]
  ]
  for (const [name, p, warm] of cases) {
    test(`${name}(${p.join(', ')}): blank until bar ${warm}, then the line drawn from the first bar`, () => {
      expect(defaults(name)[WARMUP_AT[name]]).toBe(1)
      const on = run(name, [...p, 1], long)
      const off = run(name, [...p, 0], long)
      on.forEach((r, i) => {
        if (i < warm) expect(r).toEqual({})
        else expect(r).toEqual(off[i])
      })
      expect(Object.keys(off[warm - 1]).length).toBeGreaterThan(0)
    })
  }
})
