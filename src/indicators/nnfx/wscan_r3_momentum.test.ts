import { describe, expect, test } from 'bun:test'

import type { Indicator, IndicatorTemplate, KLineData } from 'klinecharts'

import fixture from './fixtures/wscan_r3_momentum.json'
import macdBb from './macdbb'
import { ewmMean, npSum, rollingMean, vsMean, windowMean } from './pdwindow'
import { micd, micdWarmup, rccd, rccdWarmup, tdxSma } from './tdx'
import tmo from './tmo'

// Four round-3 momentum C1s of the windicators NNFX scan -- TDX's MICD and RCCD, Sierra Chart's
// MACD Bollinger Bands and pandas-ta's True Momentum Oscillator -- against windicators' own output,
// the code the scan ran (fixtures/wscan_r3_momentum.json, generated by
// notes/research/NoNonSenseForex/tests/gen_nnfx_r3_momentum.py from the windicators snapshot 0b4dcc0).
// `ma` and `state` in the fixture are the scan's reading of those outputs (nnfx.forms, wscan.core.build).

const bars: KLineData[] = fixture.bars.ts.map((timestamp, i) => ({
  timestamp,
  open: fixture.bars.open[i] as number,
  high: fixture.bars.high[i] as number,
  low: fixture.bars.low[i] as number,
  close: fixture.bars.close[i] as number,
  volume: fixture.bars.volume[i] as number
}))

type Row = Record<string, number | undefined>
const templates = new Map<string, IndicatorTemplate>(
  [micd, rccd, macdBb, tmo].map((t) => [t.name, t as unknown as IndicatorTemplate])
)
function run(name: string, calcParams: number[], data: KLineData[] = bars): Row[] {
  const t = templates.get(name)
  if (t === undefined) throw new Error(name)
  return (t.calc as (d: KLineData[], i: Indicator) => Row[])(data, { calcParams } as unknown as Indicator)
}
function defaults(name: string): number[] {
  const t = templates.get(name)
  if (t === undefined) throw new Error(name)
  return [...(t.calcParams as number[])]
}

// Each template's calcParams in order, by the names the fixture's `chart` uses.
const PARAM_ORDER: Record<string, string[]> = {
  MICD: ['smoothing', 'fast', 'slow', 'ma', 'inverted', 'warmup'],
  RCCD: ['period', 'fast', 'slow', 'ma', 'inverted', 'warmup'],
  MACD_BB: ['fast', 'slow', 'macd_length', 'devs', 'ma_type', 'ma', 'inverted'],
  TMO: ['length', 'calc', 'smooth', 'exclusive', 'mamode', 'inverted']
}
const INVERTED_AT: Record<string, number> = { MICD: 4, RCCD: 4, MACD_BB: 6, TMO: 5 }
// MICD's and RCCD's warm-ups (tdx.ts) are switched off for parity and tested on their own.
const WARMUP_AT: Record<string, number> = { MICD: 5, RCCD: 5 }

function params(template: string, chart: Record<string, number>, warmup = 0): number[] {
  const p = defaults(template)
  PARAM_ORDER[template].forEach((k, i) => {
    if (k in chart) p[i] = chart[k]
  })
  if (template in WARMUP_AT) p[WARMUP_AT[template]] = warmup
  return p
}

function near(actual: number | undefined, expected: number): boolean {
  return actual !== undefined && Math.abs(actual - expected) <= 1e-9 * Math.max(1, Math.abs(expected))
}

function caseBars(c: { open?: number[]; close?: number[] }): KLineData[] {
  return bars.map((b, i) => ({
    ...b,
    open: c.open === undefined ? b.open : c.open[i],
    close: c.close === undefined ? b.close : c.close[i]
  }))
}

describe('parity with windicators, the code the windicators NNFX scan ran', () => {
  test('the fixture is the generated one, and covers every template', () => {
    expect(fixture.$comment).toContain('gen_nnfx_r3_momentum.py')
    expect(new Set(fixture.cases.map((c) => c.template))).toEqual(new Set(Object.keys(PARAM_ORDER)))
  })

  test("each template's defaults are the scan's setting, and the fixture checks them", () => {
    expect(defaults('MICD')).toEqual([4, 15, 20, 3, 0, 1])
    expect(defaults('RCCD')).toEqual([5, 21, 14, 3, 1, 1])
    expect(defaults('MACD_BB')).toEqual([12, 20, 7, 2, 5, 3, 0])
    expect(defaults('TMO')).toEqual([14, 4, 3, 1, 0, 1])
    for (const name of Object.keys(PARAM_ORDER)) {
      const checked = fixture.cases
        .filter((c) => c.template === name && !('close' in c))
        .map((c) => params(name, c.chart as unknown as Record<string, number>, 1))
      expect(checked).toContainEqual(defaults(name))
    }
  })

  for (const c of fixture.cases) {
    const p = params(c.template, c.chart as unknown as Record<string, number>)
    const data = caseBars(c as { open?: number[]; close?: number[] })
    test(`${c.template}(${p.join(', ')}) -- ${c.source}`, () => {
      const rows = run(c.template, p, data)
      const out = c.out as unknown as Record<string, Array<number | null>>
      for (const [key, expected] of Object.entries(out)) {
        const bad: Array<{ i: number; actual: number | undefined; expected: number | null }> = []
        expected.forEach((e, i) => {
          const a = rows[i][key]
          const ok = e === null ? a === undefined : key === 'state' ? a === e : near(a, e)
          if (!ok) bad.push({ i, actual: a, expected: e })
        })
        expect({ key, bad: bad.slice(0, 5) }).toEqual({ key, bad: [] })
        expect(expected.filter((v) => v !== null).length).toBeGreaterThan(bars.length / 2)
      }
      // Nothing beyond what the fixture holds.
      for (const r of rows) for (const k of Object.keys(r)) if (r[k] !== undefined) expect(Object.keys(out)).toContain(k)
    })
  }
})

describe('causality, the reading and its settings', () => {
  for (const c of fixture.cases) {
    const p = params(c.template, c.chart as unknown as Record<string, number>)
    const data = caseBars(c as { open?: number[]; close?: number[] })
    test(`${c.template}(${p.join(', ')}): a run on a prefix is the prefix of the full run`, () => {
      const full = run(c.template, p, data)
      for (const n of [1, 2, 7, 30, 61, 120, 199, 249]) expect(run(c.template, p, data.slice(0, n))).toEqual(full.slice(0, n))
    })
  }

  for (const name of Object.keys(PARAM_ORDER)) {
    test(`${name}: "inverted" swaps long and short and changes nothing else`, () => {
      const p = defaults(name)
      if (name in WARMUP_AT) p[WARMUP_AT[name]] = 0
      const at = INVERTED_AT[name]
      const flipped = [...p]
      flipped[at] = 1 - p[at]
      const a = run(name, p)
      const b = run(name, flipped)
      a.forEach((r, i) => {
        const { state: sa, ...ra } = r
        const { state: sb, ...rb } = b[i]
        expect(rb).toEqual(ra)
        expect(sb).toBe(sa === undefined ? undefined : sa === 0 ? 0 : -sa)
      })
      expect(new Set(a.map((r) => r.state).filter((s) => s !== undefined))).toContain(1)
      expect(new Set(a.map((r) => r.state).filter((s) => s !== undefined))).toContain(-1)
    })
  }

  test("the readings the scan tested: MICD's and MACD_BB's the conventional way round, RCCD's and TMO's inverted", () => {
    expect(defaults('MICD')[INVERTED_AT.MICD]).toBe(0)
    expect(defaults('MACD_BB')[INVERTED_AT.MACD_BB]).toBe(0)
    expect(defaults('RCCD')[INVERTED_AT.RCCD]).toBe(1)
    expect(defaults('TMO')[INVERTED_AT.TMO]).toBe(1)
    // RCCD inverted: long while DIF is below its own 3-bar mean; TMO: while TMO is below the signal's momentum.
    const r = run('RCCD', params('RCCD', {}))
    const vs = vsMean(
      r.map((x) => x.dif ?? Number.NaN),
      3
    )
    r.forEach((x, i) => {
      if (x.state !== undefined) expect(x.state).toBe(vs[i] < 0 ? 1 : vs[i] > 0 ? -1 : 0)
    })
    for (const x of run('TMO', defaults('TMO'))) {
      if (x.state === undefined) continue
      const d = (x.tmo as number) - (x.signal_momentum as number)
      expect(x.state).toBe(d < 0 ? 1 : d > 0 ? -1 : 0)
    }
  })

  test("the reading is the line against its mean without the mean's rounding: a line held level reads 0", () => {
    // (0.1 + 0.1 + 0.1) / 3 is not 0.1 in floating point; the scan's form (forms.vs_sma) is exactly 0.
    const x = [0, 0.1, 0.1, 0.1, 0.2]
    expect(0.1 - windowMean(x, 3)[3]).not.toBe(0)
    const vs = vsMean(x, 3)
    expect(vs.slice(0, 2)).toEqual([Number.NaN, Number.NaN])
    expect(vs[2]).toBe((0.1 - 0 + 0 + 0) / 3)
    expect(vs[3]).toBe(0)
    expect(vs[4]).toBe((0.2 - 0.1 + (0.2 - 0.1) + 0) / 3)
  })

  test("numpy's pairwise sum: sequential below 8 values, 8 accumulators from there, split above 128", () => {
    const x = Array.from({ length: 300 }, (_, i) => 1.1 + Math.sin(i) * 1e-3)
    let seq = 0
    for (let i = 0; i < 5; i++) seq += x[i]
    expect(npSum(x, 0, 5)).toBe(seq)
    const r = x.slice(0, 8)
    for (let i = 8; i < 16; i++) r[i - 8] += x[i]
    expect(npSum(x, 0, 17)).toBe(r[0] + r[1] + (r[2] + r[3]) + (r[4] + r[5] + (r[6] + r[7])) + x[16])
    expect(npSum(x, 0, 300)).toBe(npSum(x, 0, 144) + npSum(x, 144, 156))
  })

  test('MACD_BB: an MA type windicators does not offer is SIMPLE, as in Sierra', () => {
    const simple = run('MACD_BB', [12, 20, 7, 2, 2, 3, 0])
    expect(run('MACD_BB', [12, 20, 7, 2, 1, 3, 0])).toEqual(simple)
    expect(run('MACD_BB', [12, 20, 7, 2, 9, 3, 0])).toEqual(simple)
    expect(run('MACD_BB', [12, 20, 7, 2, 5, 3, 0])).not.toEqual(run('MACD_BB', [12, 20, 7, 2, 0, 3, 0]))
  })

  test('MACD_BB: nothing before bar 2 x macd length + max(fast, slow), where Sierra starts drawing', () => {
    const rows = run('MACD_BB', defaults('MACD_BB'))
    const first = 2 * 7 + 20
    rows.forEach((r, i) => {
      if (i < first) expect(r.upper).toBeUndefined()
      else expect(r.upper).toBeDefined()
    })
  })

  test("TMO: pandas-ta's inclusive window needs two opens, so its length is at least 2", () => {
    expect(run('TMO', [1, 4, 3, 0, 0, 1])).toEqual(run('TMO', [2, 4, 3, 0, 0, 1]))
    expect(run('TMO', [1, 4, 3, 1, 0, 1])).not.toEqual(run('TMO', [2, 4, 3, 1, 0, 1]))
  })
})

describe("the window arithmetic the four share, bit for bit (pdwindow.ts against windicators' and numpy's own)", () => {
  const P = fixture.primitives as unknown as {
    x: Record<string, Array<number | null>>
    coms: Record<string, number>
    rolling: Record<string, Record<string, Array<number | null>>>
    ewm: Record<string, Record<string, Array<number | null>>>
    sums: Record<string, Array<number | null>>
    vs_sma: Record<string, Array<number | null>>
    sma: Record<string, Array<number | null>>
  }
  const nan = (xs: Array<number | null>) => xs.map((v) => (v === null ? Number.NaN : v))
  // toEqual compares numbers with Object.is: NaN equals NaN, and every bit counts.
  for (const s of ['a', 'b']) {
    test(`pandas' rolling(w).mean() on series ${s}, w = 1, 2, 3, 7, 20`, () => {
      for (const [w, expected] of Object.entries(P.rolling[s])) expect(rollingMean(nan(P.x[s]), Number(w))).toEqual(nan(expected))
    })
    test(`pandas' ewm(com, adjust=False).mean() on series ${s}, TDX alphas 1/4 and 1/10, span 3, alpha 1`, () => {
      for (const [k, expected] of Object.entries(P.ewm[s])) expect(ewmMean(nan(P.x[s]), P.coms[k])).toEqual(nan(expected))
    })
  }
  test('the TDX SMA reaches its alpha through pandas\' centre of mass, as windicators does', () => {
    expect(tdxSma(nan(P.x.a), 4, 1)).toEqual(nan(P.ewm.a.tdx4))
    expect(tdxSma(nan(P.x.b), 10, 1)).toEqual(nan(P.ewm.b.tdx10))
  })
  test("numpy's window sums, and the scan's exact mean and vs_sma", () => {
    const x = nan(P.x.finite)
    for (const [k, expected] of Object.entries(P.sums)) {
      const n = Number(k)
      expect(x.slice(n - 1).map((_, i) => npSum(x, i, n))).toEqual(nan(expected))
    }
    for (const [k, expected] of Object.entries(P.sma)) expect(windowMean(x, Number(k))).toEqual(nan(expected))
    for (const [k, expected] of Object.entries(P.vs_sma)) expect(vsMean(x, Number(k))).toEqual(nan(expected))
  })
})

describe('the warm-ups of the recursive ones', () => {
  test('MICD and RCCD: the warm-up rule, its start and the 1e-4 seed decay, at the scan setting and the sources\' defaults', () => {
    // max(fast, slow) + 1, plus (1 - min(1 / smoothing, 0.1))^k < 1e-4: 0.9^88 = 9.4e-5.
    expect(micdWarmup(4, 15, 20)).toBe(109)
    expect(micdWarmup(3, 10, 20)).toBe(109)
    expect(micdWarmup(20, 15, 20)).toBe(21 + 180)
    // period + 1 + max(fast, slow), plus (1 - 1 / period)^k < 1e-4: 0.8^42 = 8.5e-5.
    expect(rccdWarmup(5, 21, 14)).toBe(69)
    expect(rccdWarmup(10, 21, 28)).toBe(127)
    expect(rccdWarmup(1, 1, 4)).toBe(6)
  })

  for (const [name, warm] of [
    ['MICD', 109],
    ['RCCD', 69]
  ] as Array<[string, number]>) {
    test(`${name}: blank for the first ${warm} bars with warm-up 1 (the default), then the lines drawn from the first bar`, () => {
      expect(defaults(name)[WARMUP_AT[name]]).toBe(1)
      const on = run(name, defaults(name))
      const p = defaults(name)
      p[WARMUP_AT[name]] = 0
      const off = run(name, p)
      on.forEach((r, i) => {
        if (i < warm) expect(r).toEqual({})
        else expect(r).toEqual(off[i])
      })
      expect(off[warm - 1].state).toBeDefined()
      expect(off[warm - 30].state).toBeDefined()
    })
  }
})
